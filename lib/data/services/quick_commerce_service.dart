  static List<QuickCommerceProductModel> getProductsByStore(QuickCommerceStore store) {
    return products.where((p) => p.store == store).toList();
  }

  static List<QuickCommerceProductModel> getProductsByCategory(IngredientCategory category) {
    return products.where((p) => p.category == category).toList();
  }

  static List<QuickCommerceProductModel> getFlashDeals() {
    return products.where((p) => p.discountPercentage >= 25).toList();
  }

  static List<QuickCommerceProductModel> getRestaurantKits() {
    return products.where((p) => p.store == QuickCommerceStore.jeerolaKitchen).toList();
  }

  static List<QuickCommerceProductModel> search(String query) {
    if (query.trim().isEmpty) return products;
    final q = query.toLowerCase();
    return products.where((p) {
      return p.title.toLowerCase().contains(q) ||
          p.brand.toLowerCase().contains(q) ||
          p.badgeText.toLowerCase().contains(q) ||
          p.store.displayName.toLowerCase().contains(q);
    }).toList();
  }
