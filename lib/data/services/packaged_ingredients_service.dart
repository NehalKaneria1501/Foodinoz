  static List<PackagedIngredientItem> getByCategory(IngredientCategory category) {
    return allItems.where((item) => item.category == category).toList();
  }

  static List<PackagedIngredientItem> searchAndFilter({
    String query = '',
    IngredientCategory? category,
    bool? jainOnly,
    bool? swaminarayanOnly,
    bool? hingFreeOnly,
  }) {
    return allItems.where((item) {
      if (category != null && item.category != category) {
        return false;
      }

      if (query.isNotEmpty) {
        final q = query.toLowerCase();
        final matchName = item.name.toLowerCase().contains(q);
        final matchSub = item.subtitle.toLowerCase().contains(q);
        if (!matchName && !matchSub) return false;
      }

      if (jainOnly == true && !item.isJain && item.category != IngredientCategory.faraliSpecial) {
        return false;
      }

      if (swaminarayanOnly == true && !item.isSwaminarayan && item.category != IngredientCategory.faraliSpecial) {
        return false;
      }

      if (hingFreeOnly == true && !item.isHingFree) {
        return false;
      }

      return true;
    }).toList();
  }
